@dataclass(slots=True)
class BootstrapResult:
    root: str
    dry_run: bool
    update_managed: bool
    created: list[str] = field(default_factory=list)
    updated: list[str] = field(default_factory=list)
    pending_updates: list[str] = field(default_factory=list)
    stale_managed: list[str] = field(default_factory=list)
    unchanged: list[str] = field(default_factory=list)
    conflicts: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    discovery: dict[str, Any] = field(default_factory=dict)

    @property
    def ok(self) -> bool:
        return not self.conflicts and not self.pending_updates and not self.stale_managed

    def to_dict(self) -> dict[str, Any]:
        return {
            "ok": self.ok,
            "root": self.root,
            "dry_run": self.dry_run,
            "update_managed": self.update_managed,
            "created": self.created,
            "updated": self.updated,
            "pending_updates": self.pending_updates,
            "stale_managed": self.stale_managed,
            "unchanged": self.unchanged,
            "conflicts": self.conflicts,
            "notes": self.notes,
            "discovery": self.discovery,
        }


@dataclass(frozen=True, slots=True)
class BootstrapReceiptAudit:
    """Read-only comparison of a bootstrap receipt with its managed files."""

    managed_count: int
    missing: tuple[str, ...]
    hash_mismatches: tuple[str, ...]
    unsafe_or_unreadable: tuple[str, ...]

    @property
    def ok(self) -> bool:
        return not (self.missing or self.hash_mismatches or self.unsafe_or_unreadable)


def bootstrap_project(
    root: Path,
    *,
    power_root: Path | None = None,
    dry_run: bool = False,
    update_managed: bool = False,
) -> BootstrapResult:
    root = root.resolve()
    if not root.is_dir():
        raise ValueError(f"project root does not exist: {root}")
    with _bootstrap_lock(root):
        return _bootstrap_project_locked(
            root,
            power_root=power_root,
            dry_run=dry_run,
            update_managed=update_managed,
        )


def _bootstrap_project_locked(
    root: Path,
    *,
    power_root: Path | None,
    dry_run: bool,
    update_managed: bool,
) -> BootstrapResult:
    cache_root = workspace_path(root, Path(".pstack"))
    if power_root is not None:
        requested_asset_root = Path(os.path.abspath(power_root))
        if _same_or_descendant(requested_asset_root, cache_root):
            _raise_cached_authority()
        asset_root = _resolve_power_source(power_root)
        source_package = asset_root / "src" / "pstack_kiro"
    else:
        checkout_root = Path(__file__).resolve().parents[2]
        checkout_package = checkout_root / "src" / "pstack_kiro"
        if checkout_package.is_dir():
            asset_root = checkout_root
            source_package = checkout_package
        else:
            source_package = Path(__file__).resolve().parent
            asset_root = source_package / "_assets"
    if _same_or_descendant(asset_root, cache_root):
        _raise_cached_authority()
    template_root = asset_root / "templates" / "project"
    if not source_package.is_dir():
        raise ValueError(f"{DISPLAY_NAME} source package is missing: {source_package}")
    _validate_power_assets(asset_root, source_package)
    projectctl_lock = asset_root / "templates" / "projectctl" / "uv.lock"

    receipt_path = workspace_path(root, RECEIPT)
    if receipt_path.exists() and not receipt_path.is_file():
        raise ValueError(f"{DISPLAY_NAME} ownership receipt path is not a file: {receipt_path}")
    old_receipt = _load_receipt(root)
    previous_hashes = old_receipt.get("files", {}) if old_receipt else {}
    operations: list[tuple[Path, bytes, bool]] = []
    notes: list[str] = []

    for source in sorted(source_package.glob("*.py")):
        relative = Path(".pstack/projectctl/src/pstack_kiro") / source.name
        operations.append((relative, source.read_bytes(), False))

    asset_sources = (
        (asset_root / "skills", Path(".kiro/skills"), Path(".pstack/projectctl/skills")),
        (
            asset_root / "dev.kiro" / "steering",
            Path(".kiro/steering"),
            Path(".pstack/projectctl/dev.kiro/steering"),
        ),
    )
    for directory, destination_base, cache_base in asset_sources:
        if not directory.is_dir():
            notes.append(f"Optional Kiro asset source is absent: {directory}")
            continue
        for source in sorted(path for path in directory.rglob("*") if path.is_file()):
            suffix = source.relative_to(directory)
            executable = os.access(source, os.X_OK)
            content = source.read_bytes()
            # The setup skill must keep its Power-local origin so an upgraded
            # Power cannot be shadowed by a stale workspace copy.
            if not (
                destination_base == Path(".kiro/skills")
                and suffix.parts
                and suffix.parts[0] == "setup-pk-stack"
            ):
                operations.append((destination_base / suffix, content, executable))
            operations.append((cache_base / suffix, content, executable))

    generated = {
        Path(".pstack/projectctl/pyproject.toml"): TARGET_PYPROJECT.encode(),
        Path(".pstack/projectctl/uv.lock"): projectctl_lock.read_bytes(),
        Path(".pstack/projectctl/templates/projectctl/uv.lock"): projectctl_lock.read_bytes(),
        Path(".pstack/projectctl/README.md"): TARGET_README.encode(),
        Path(".pstack/bin/projectctl"): INTERNAL_WRAPPER.encode(),
        Path("Wiki/index.md"): _render_wiki_index(root).encode(),
        Path("Wiki/features/README.md"): _render_feature_readme(root).encode(),
    }
    for relative, content in generated.items():
        operations.append((relative, content, relative == Path(".pstack/bin/projectctl")))

    if template_root.is_dir():
        for source in sorted(path for path in template_root.rglob("*") if path.is_file()):
            relative = source.relative_to(template_root)
            cached = Path(".pstack/projectctl/templates/project") / relative
            executable = os.access(source, os.X_OK)
            operations.extend(
                (
                    (relative, source.read_bytes(), executable),
                    (cached, source.read_bytes(), executable),
                )
            )
    else:
        notes.append(f"No project templates were found at {template_root}.")

    root_wrapper = root / "projectctl"
    if not root_wrapper.exists() or "projectctl" in previous_hashes:
        operations.append((Path("projectctl"), ROOT_WRAPPER.encode(), True))
    else:
        notes.append(
            "An existing root projectctl was preserved; use .pstack/bin/projectctl or integrate "
            f"the {DISPLAY_NAME} commands into the existing project CLI."
        )

    initial_discovery = discover_repository(root)
    initial_discovery_content = (
        json.dumps(initial_discovery, indent=2, sort_keys=True) + "\n"
    ).encode()
    preview_operations = [*operations, (DISCOVERY, initial_discovery_content, False)]
    preview = BootstrapResult(
        root=str(root),
        dry_run=True,
        update_managed=update_managed,
        notes=list(notes),
        discovery=initial_discovery,
    )
    preview_hashes: dict[str, str] = {}
    for relative, content, executable in preview_operations:
        _apply_file(
            root,
            relative,
            content,
            previous_hashes=previous_hashes,
            managed_hashes=preview_hashes,
            result=preview,
            update_managed=update_managed,
            executable=executable,
            refresh_owned=relative == DISCOVERY,
        )
    current_keys = {relative.as_posix() for relative, _, _ in preview_operations}
    for key in sorted(set(previous_hashes) - current_keys):
        stale_path = workspace_path(root, Path(key))
        if stale_path.exists():
            preview.stale_managed.append(key)
    _ensure_gitignore(root, result=preview, dry_run=True)
    if not preview.ok:
        preview.dry_run = dry_run
        preview.notes.append("No managed files were written because preflight found blockers.")
        return preview
    if dry_run:
        return preview

    result = BootstrapResult(
        root=str(root),
        dry_run=False,
        update_managed=update_managed,
        notes=notes,
    )
    managed_hashes: dict[str, str] = {}
    for relative, content, executable in operations:
        _apply_file(
            root,
            relative,
            content,
            previous_hashes=previous_hashes,
            managed_hashes=managed_hashes,
            result=result,
            update_managed=update_managed,
            executable=executable,
        )
    _ensure_gitignore(root, result=result, dry_run=False)
    result.discovery = discover_repository(root)
    discovery_content = (json.dumps(result.discovery, indent=2, sort_keys=True) + "\n").encode()
    _apply_file(
        root,
        DISCOVERY,
        discovery_content,
        previous_hashes=previous_hashes,
        managed_hashes=managed_hashes,
        result=result,
        update_managed=update_managed,
        refresh_owned=True,
    )
    if not result.ok:
        result.notes.append(
            "Workspace contents changed after preflight; no ownership receipt was committed."
        )
        return result

    receipt_payload = {
        "schema_version": BOOTSTRAP_SCHEMA,
        "manager": RECEIPT_MANAGER,
        "files": dict(sorted(managed_hashes.items())),
    }
    _verify_managed_hashes(root, managed_hashes)
    receipt_content = (json.dumps(receipt_payload, indent=2, sort_keys=True) + "\n").encode()
    _write_if_changed(workspace_path(root, RECEIPT), receipt_content, executable=False)
    return result


@contextmanager
def _bootstrap_lock(root: Path) -> Iterator[None]:
    """Serialize setup without creating a project file during preflight."""

    if fcntl is None:
        raise OSError(f"{DISPLAY_NAME} setup requires fcntl locking on this platform")
    flags = os.O_RDONLY | getattr(os, "O_DIRECTORY", 0) | getattr(os, "O_CLOEXEC", 0)
    descriptor = os.open(root, flags)
    try:
        fcntl.flock(descriptor, fcntl.LOCK_EX)
        yield
    finally:
        fcntl.flock(descriptor, fcntl.LOCK_UN)
        os.close(descriptor)


def _verify_managed_hashes(root: Path, managed_hashes: dict[str, str]) -> None:
    audit = _audit_managed_hashes(root, managed_hashes)
    failures = sorted((*audit.missing, *audit.hash_mismatches, *audit.unsafe_or_unreadable))
    if failures:
        raise OSError(
            "managed files changed during setup before receipt commit: " + ", ".join(failures)
        )


def audit_bootstrap_receipt(root: Path) -> BootstrapReceiptAudit:
    """Validate and audit every managed path in the bootstrap receipt without writing."""

    receipt_path = workspace_path(root, RECEIPT)
    if not receipt_path.exists():
        raise ValueError(f"{DISPLAY_NAME} ownership receipt is missing at {receipt_path}")
    if not receipt_path.is_file():
        raise ValueError(f"{DISPLAY_NAME} ownership receipt is not a file at {receipt_path}")
    receipt = _load_receipt(root)
    if receipt is None:  # Defensive: existence and type were checked above.
        raise ValueError(f"{DISPLAY_NAME} ownership receipt is missing at {receipt_path}")
    managed_hashes: dict[str, str] = receipt["files"]
    return _audit_managed_hashes(root, managed_hashes)


def _audit_managed_hashes(root: Path, managed_hashes: dict[str, str]) -> BootstrapReceiptAudit:
    missing: list[str] = []
    hash_mismatches: list[str] = []
    unsafe_or_unreadable: list[str] = []
    for key, expected in sorted(managed_hashes.items()):
        try:
            path = workspace_path(root, Path(key))
            if not path.is_file():
                missing.append(key)
            elif _hash(path.read_bytes()) != expected:
                hash_mismatches.append(key)
        except (OSError, ValueError):
            unsafe_or_unreadable.append(key)
    return BootstrapReceiptAudit(
        managed_count=len(managed_hashes),
        missing=tuple(missing),
        hash_mismatches=tuple(hash_mismatches),
        unsafe_or_unreadable=tuple(unsafe_or_unreadable),
    )


def _load_receipt(root: Path) -> dict[str, Any] | None:
    path = workspace_path(root, RECEIPT)
    if not path.is_file():
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"invalid {DISPLAY_NAME} ownership receipt at {path}: {exc}") from exc
    if not isinstance(data, dict):
        raise ValueError(f"{DISPLAY_NAME} ownership receipt must be a JSON object at {path}")
    if (
        type(data.get("schema_version")) is not int
        or data["schema_version"] != BOOTSTRAP_SCHEMA
        or type(data.get("manager")) is not str
        or data["manager"] != RECEIPT_MANAGER
    ):
        raise ValueError(f"unrecognized {DISPLAY_NAME} ownership receipt at {path}")
    files = data.get("files")
    if (
        not isinstance(files, dict)
        or not files
        or not all(
            _valid_receipt_key(key)
            and isinstance(value, str)
            and re.fullmatch(r"[0-9a-f]{64}", value)
            for key, value in files.items()
        )
    ):
        raise ValueError(
            f"invalid managed-file hashes in {DISPLAY_NAME} ownership receipt at {path}"
        )
    return data


def _valid_receipt_key(value: Any) -> bool:
    if type(value) is not str or not value:
        return False
    path = Path(value)
    return (
        not path.is_absolute()
        and path.as_posix() == value
        and all(part not in {"", ".", ".."} for part in path.parts)
    )


def _validate_power_assets(asset_root: Path, source_package: Path) -> None:
    try:
        source_relative = source_package.relative_to(asset_root)
    except ValueError:
        ensure_tree_no_symlinks(source_package.parent, Path(source_package.name))
    else:
        ensure_tree_no_symlinks(asset_root, source_relative)
    for relative in (
        "skills",
        "docs",
        "dev.kiro/steering",
        "templates/project",
        "templates/projectctl",
    ):
        ensure_tree_no_symlinks(asset_root, Path(relative))
    missing = [
        f"src/pstack_kiro/{name}"
        for name in REQUIRED_SOURCE_MODULES
        if not (source_package / name).is_file()
    ]
    missing.extend(
        relative for relative in REQUIRED_POWER_ASSETS if not (asset_root / relative).is_file()
    )
    if missing:
        joined = ", ".join(sorted(missing))
        raise ValueError(f"required {DISPLAY_NAME} Power assets are missing: {joined}")
    _validate_skill_catalog(asset_root)


def _validate_skill_catalog(asset_root: Path) -> tuple[str, ...]:
    """Require Cursor parity, PK-only, and curated skills to be one safe catalog.

    ``upstream-skill-parity.json`` remains deliberately scoped to the Cursor
    source.  Curated skills have their own registry and bundle manifests so a
    new reviewed source can be added without changing the Cursor parity
    schema.  Bootstrap still exposes one exact set of skill directories to
    the generated workspace.
    """

    path = asset_root / SKILL_PARITY_ASSET
    try:
        raw = path.read_bytes()
    except OSError as exc:
        raise ValueError(f"unable to read {DISPLAY_NAME} skill parity catalog: {path}") from exc
    if len(raw) > MAX_SKILL_PARITY_BYTES:
        raise ValueError(
            f"{DISPLAY_NAME} skill parity catalog exceeds {MAX_SKILL_PARITY_BYTES} bytes"
        )
    try:
        document = json.loads(raw)
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ValueError(f"invalid {DISPLAY_NAME} skill parity catalog: {exc}") from exc
    if not isinstance(document, dict) or document.get("schema_version") != 1:
        raise ValueError(f"invalid {DISPLAY_NAME} skill parity catalog schema")
    raw_skills = document.get("skills")
    raw_pk_only = document.get("pk_only_skills")
    if not isinstance(raw_skills, list) or not raw_skills:
        raise ValueError(f"invalid {DISPLAY_NAME} upstream skill inventory")
    if not isinstance(raw_pk_only, list):
        raise ValueError(f"invalid {DISPLAY_NAME} PK-only skill inventory")

    upstream_names: list[str] = []
    routed_names: list[str] = []
    for index, entry in enumerate(raw_skills):
        if not isinstance(entry, dict):
            raise ValueError(f"skill parity entry {index} must be an object")
        name = entry.get("name")
        disposition = entry.get("disposition")
        target = entry.get("target")
        if type(name) is not str or not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name):
            raise ValueError(f"skill parity entry {index} has an invalid name")
        upstream_names.append(name)
        if disposition not in ALLOWED_SKILL_DISPOSITIONS:
            raise ValueError(f"skill parity entry {name!r} has an invalid disposition")
        if disposition == "excluded":
            if target is not None:
                raise ValueError(f"excluded skill {name!r} must not have a runnable target")
            continue
        expected_target = f"skills/{SKILL_ROUTE_ALIASES.get(name, name)}/SKILL.md"
        if target != expected_target:
            raise ValueError(f"routed skill {name!r} must target its canonical skill file")
        # The upstream name is provenance; the target's directory is the
        # canonical Kiro route and may intentionally adapt the slash command.
        routed_names.append(Path(target).parent.name)
    pk_only = [
        name
        for name in raw_pk_only
        if type(name) is str and re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name)
    ]
    if len(pk_only) != len(raw_pk_only):
        raise ValueError(f"invalid {DISPLAY_NAME} PK-only skill name")
    if upstream_names != sorted(set(upstream_names)):
        raise ValueError(f"{DISPLAY_NAME} upstream skill inventory must be sorted and unique")
    if pk_only != sorted(set(pk_only)) or set(pk_only) & set(upstream_names):
        raise ValueError(f"{DISPLAY_NAME} PK-only skill inventory must be sorted and disjoint")

    cursor_expected = set(routed_names) | set(pk_only)
    summary = document.get("summary")

    curated_names = _validate_curated_registry(asset_root, forbidden=cursor_expected)
    expected = cursor_expected | set(curated_names)
    skill_root = ensure_tree_no_symlinks(asset_root, Path("skills"))
    _validate_case_collisions(skill_root, context=f"{DISPLAY_NAME} skill catalog")
    actual = {
        child.name
        for child in skill_root.iterdir()
        if child.is_dir() and (child / "SKILL.md").is_file()
    }
    unexpected_directories = sorted(
        child.name
        for child in skill_root.iterdir()
        if child.is_dir() and not (child / "SKILL.md").is_file()
    )
    if actual != expected or unexpected_directories:
        missing = sorted(expected - actual)
        extra = sorted(actual - expected)
        details: list[str] = []
        if missing:
            details.append("missing " + ", ".join(missing))
        if extra:
            details.append("unexpected " + ", ".join(extra))
        if unexpected_directories:
            details.append("directories without SKILL.md " + ", ".join(unexpected_directories))
        raise ValueError(f"{DISPLAY_NAME} skill catalog mismatch: {'; '.join(details)}")
    if not isinstance(summary, dict):
        raise ValueError(f"{DISPLAY_NAME} skill parity summary is invalid")
    if summary.get("shipped_skill_directories") != len(cursor_expected):
        raise ValueError(f"{DISPLAY_NAME} skill parity summary does not match the catalog")
    return tuple(sorted(expected))


_CURATED_REGISTRY_KEYS = {"schema_version", "registry_type", "skills", "summary"}
_CURATED_SKILL_KEYS = {
    "name",
    "source_id",
    "target",
    "bundle_root",
    "bundle_manifest",
    "source_parity",
    "provenance",
}
_CURATED_BUNDLE_KEYS = {
    "schema_version",
    "artifact_type",
    "skill",
    "bundle_root",
    "files",
    "summary",
}
_CURATED_BUNDLE_FILE_KEYS = {"path", "sha256", "size", "mode", "source_path", "handling"}


def _validate_curated_registry(asset_root: Path, *, forbidden: set[str]) -> tuple[str, ...]:
    """Validate the independent curated-skill registry and its exact bundles."""

    path = asset_root / CURATED_SKILLS_ASSET
    try:
        raw = path.read_bytes()
    except OSError as exc:
        raise ValueError(f"unable to read {DISPLAY_NAME} curated skill registry: {path}") from exc
    if len(raw) > MAX_CURATED_REGISTRY_BYTES:
        raise ValueError(
            f"{DISPLAY_NAME} curated skill registry exceeds {MAX_CURATED_REGISTRY_BYTES} bytes"
        )
    try:
        document = json.loads(raw)
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ValueError(f"invalid {DISPLAY_NAME} curated skill registry: {exc}") from exc
    if not isinstance(document, dict) or set(document) != _CURATED_REGISTRY_KEYS:
        raise ValueError(f"invalid {DISPLAY_NAME} curated skill registry schema")
    if document.get("schema_version") != 1 or document.get("registry_type") != "curated-skills":
        raise ValueError(f"invalid {DISPLAY_NAME} curated skill registry schema")
    entries = document.get("skills")
    if not isinstance(entries, list) or not entries:
        raise ValueError(f"invalid {DISPLAY_NAME} curated skill inventory")

    names: list[str] = []
    for index, entry in enumerate(entries):
        if not isinstance(entry, dict) or set(entry) != _CURATED_SKILL_KEYS:
            raise ValueError(f"curated skill entry {index} has invalid fields")
        name = entry.get("name")
        if type(name) is not str or not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name):
            raise ValueError(f"curated skill entry {index} has an invalid name")
        names.append(name)
        if name in forbidden:
            raise ValueError(f"curated skill {name!r} duplicates a Cursor or PK-only skill")
        source_id = entry.get("source_id")
        if type(source_id) is not str or not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", source_id):
            raise ValueError(f"curated skill {name!r} has an invalid source_id")
        target = entry.get("target")
        if target != f"skills/{name}/SKILL.md":
            raise ValueError(f"curated skill {name!r} must target its canonical skill file")
        for key, suffix in (
            ("bundle_root", ""),
            ("bundle_manifest", ".json"),
            ("source_parity", ".json"),
            ("provenance", ".md"),
        ):
            value = entry.get(key)
            if type(value) is not str or not _valid_posix_relative(value):
                raise ValueError(f"curated skill {name!r} has an unsafe {key}")
            if suffix and not value.endswith(suffix):
                raise ValueError(f"curated skill {name!r} {key} has an invalid suffix")
        if entry["bundle_root"] != f"skills/{name}":
            raise ValueError(f"curated skill {name!r} bundle_root must be its canonical directory")
        for key in ("bundle_manifest", "source_parity", "provenance"):
            referenced = asset_root / entry[key]
            if not referenced.is_file() or referenced.is_symlink():
                raise ValueError(f"curated skill {name!r} {key} is missing or unsafe")
        _validate_curated_bundle_manifest(asset_root, entry)

    if names != sorted(set(names)):
        raise ValueError(f"{DISPLAY_NAME} curated skill inventory must be sorted and unique")
    shared_sources: dict[str, tuple[str, str]] = {}
    for entry in entries:
        source_id = entry["source_id"]
        identity = (entry["source_parity"], entry["provenance"])
        previous = shared_sources.setdefault(source_id, identity)
        if previous != identity:
            raise ValueError(
                f"{DISPLAY_NAME} curated skills sharing a source must share parity and provenance"
            )
    summary = document.get("summary")
    if not isinstance(summary, dict) or set(summary) != {
        "curated_skill_count",
        "shipped_skill_directories",
        "bundle_file_count",
    }:
        raise ValueError(f"{DISPLAY_NAME} curated skill summary is invalid")
    bundle_file_count = sum(
        _bundle_file_count(asset_root / entry["bundle_manifest"])
        for entry in entries
        if isinstance(entry, dict)
    )
    if summary != {
        "curated_skill_count": len(entries),
        "shipped_skill_directories": len(entries),
        "bundle_file_count": bundle_file_count,
    }:
        raise ValueError(f"{DISPLAY_NAME} curated skill summary does not match the registry")
    return tuple(names)


def _validate_curated_bundle_manifest(asset_root: Path, entry: dict[str, Any]) -> None:
    name = entry["name"]
    manifest_path = asset_root / entry["bundle_manifest"]
    try:
        raw = manifest_path.read_bytes()
    except OSError as exc:
        raise ValueError(f"unable to read curated bundle manifest for {name!r}") from exc
    if len(raw) > MAX_CURATED_BUNDLE_BYTES:
        raise ValueError(f"curated bundle manifest for {name!r} exceeds the byte limit")
    try:
        document = json.loads(raw)
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ValueError(f"invalid curated bundle manifest for {name!r}: {exc}") from exc
    if not isinstance(document, dict) or set(document) != _CURATED_BUNDLE_KEYS:
        raise ValueError(f"invalid curated bundle manifest schema for {name!r}")
    if document.get("schema_version") != 1 or document.get("artifact_type") != "curated-bundle":
        raise ValueError(f"invalid curated bundle manifest schema for {name!r}")
    if document.get("skill") != name or document.get("bundle_root") != entry["bundle_root"]:
        raise ValueError(f"curated bundle manifest for {name!r} does not bind its registry entry")
    bundle_root = asset_root / entry["bundle_root"]
    if not bundle_root.is_dir() or bundle_root.is_symlink():
        raise ValueError(f"curated bundle root for {name!r} is missing or unsafe")
    ensure_tree_no_symlinks(asset_root, Path(entry["bundle_root"]))
    files = document.get("files")
    if not isinstance(files, list) or not files:
        raise ValueError(f"curated bundle manifest for {name!r} has no files")
    paths: list[str] = []
    for index, item in enumerate(files):
        if not isinstance(item, dict) or set(item) != _CURATED_BUNDLE_FILE_KEYS:
            raise ValueError(f"curated bundle file {name!r} index {index} has invalid fields")
        relative = item.get("path")
        if type(relative) is not str or not _valid_posix_relative(relative):
            raise ValueError(f"curated bundle file {name!r} index {index} has an unsafe path")
        paths.append(relative)
        if type(item.get("sha256")) is not str or not re.fullmatch(r"[0-9a-f]{64}", item["sha256"]):
            raise ValueError(f"curated bundle file {name!r} index {index} has an invalid hash")
        if type(item.get("size")) is not int or item["size"] < 0:
            raise ValueError(f"curated bundle file {name!r} index {index} has an invalid size")
        if item.get("mode") not in {"100644", "100755"}:
            raise ValueError(f"curated bundle file {name!r} index {index} has an invalid mode")
        source_path = item.get("source_path")
        if type(source_path) is not str or not _valid_posix_relative(source_path):
            raise ValueError(
                f"curated bundle file {name!r} index {index} has an unsafe source path"
            )
        if type(item.get("handling")) is not str or not item["handling"].strip():
            raise ValueError(f"curated bundle file {name!r} index {index} has no handling")
        target = workspace_path(asset_root, Path(entry["bundle_root"]) / relative)
        if not target.is_file() or target.is_symlink():
            raise ValueError(f"curated bundle file {name!r} is missing or unsafe: {relative}")
        actual = target.read_bytes()
        if len(actual) != item["size"] or _hash(actual) != item["sha256"]:
            raise ValueError(f"curated bundle file {name!r} hash or size mismatch: {relative}")
        actual_mode = "100755" if target.stat().st_mode & 0o111 else "100644"
        if actual_mode != item["mode"]:
            raise ValueError(f"curated bundle file {name!r} mode mismatch: {relative}")
    if paths != sorted(set(paths), key=str.casefold):
        raise ValueError(f"curated bundle manifest for {name!r} paths must be sorted and unique")
    actual_paths = sorted(
        [
            path.relative_to(bundle_root).as_posix()
            for path in bundle_root.rglob("*")
            if path.is_file()
        ],
        key=str.casefold,
    )
    if actual_paths != paths:
        raise ValueError(f"curated bundle manifest for {name!r} does not match its exact files")
    _validate_case_collisions(bundle_root, context=f"curated bundle {name}")
    summary = document.get("summary")
    if not isinstance(summary, dict) or set(summary) != {"file_count", "byte_count"}:
        raise ValueError(f"curated bundle summary for {name!r} is invalid")
    if summary != {
        "file_count": len(files),
        "byte_count": sum(item["size"] for item in files),
    }:
        raise ValueError(f"curated bundle summary for {name!r} does not match its files")


def _bundle_file_count(path: Path) -> int:
    try:
        document = json.loads(path.read_bytes())
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ValueError(f"unable to read curated bundle manifest: {path}") from exc
    files = document.get("files") if isinstance(document, dict) else None
    if not isinstance(files, list):
        raise ValueError(f"curated bundle manifest files are invalid: {path}")
    return len(files)


def _valid_posix_relative(value: Any) -> bool:
    if type(value) is not str or not value or value.startswith("/") or "\\" in value:
        return False
    path = PurePosixPath(value)
    return path.as_posix() == value and all(part not in {"", ".", ".."} for part in path.parts)


def _validate_case_collisions(root: Path, *, context: str) -> None:
    """Reject case-fold aliases that are ambiguous on macOS and Windows."""

    seen: dict[str, str] = {}
    if not root.exists():
        return
    for path in sorted(root.rglob("*")):
        relative = path.relative_to(root).as_posix()
        folded = relative.casefold()
        previous = seen.get(folded)
        if previous is not None and previous != relative:
            raise ValueError(f"{context} has a case-collision: {previous} and {relative}")
        seen[folded] = relative


def _resolve_power_source(path: Path) -> Path:
    try:
        return path.resolve()
    except (OSError, RuntimeError, ValueError) as exc:
        raise WorkspacePathError(f"unable to resolve the {DISPLAY_NAME} Power source path") from exc


def _same_or_descendant(candidate: Path, boundary: Path) -> bool:
    """Use lexical ancestry plus filesystem identity for case-folding volumes."""

    candidate_absolute = Path(os.path.abspath(candidate))
    boundary_absolute = Path(os.path.abspath(boundary))
    try:
        candidate_absolute.relative_to(boundary_absolute)
    except ValueError:
        pass
    else:
        return True

    if not boundary_absolute.exists():
        return False
    for ancestor in (candidate_absolute, *candidate_absolute.parents):
        if not ancestor.exists():
            continue
        try:
            if ancestor.samefile(boundary_absolute):
                return True
        except OSError as exc:
            raise WorkspacePathError(
                f"unable to compare the {DISPLAY_NAME} Power source path"
            ) from exc
    return False


