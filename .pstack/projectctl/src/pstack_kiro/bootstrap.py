def _apply_file(
    root: Path,
    relative: Path,
    content: bytes,
    *,
    previous_hashes: dict[str, str],
    managed_hashes: dict[str, str],
    result: BootstrapResult,
    update_managed: bool,
    executable: bool = False,
    refresh_owned: bool = False,
) -> None:
    key = relative.as_posix()
    destination = workspace_path(root, relative)
    parent_blocker = _existing_parent_blocker(root, relative)
    if parent_blocker is not None:
        if parent_blocker not in result.conflicts:
            result.conflicts.append(parent_blocker)
        return
    if destination.exists() and not destination.is_file():
        result.conflicts.append(key)
        return
    desired_hash = _hash(content)
    previous_hash = previous_hashes.get(key)
    existing_hash = _hash(destination.read_bytes()) if destination.is_file() else None

    if existing_hash == desired_hash:
        managed_hashes[key] = desired_hash
        result.unchanged.append(key)
        if not result.dry_run:
            destination.chmod(0o755 if executable else 0o644)
        return
    if existing_hash is not None:
        if existing_hash != previous_hash:
            if previous_hash is not None:
                managed_hashes[key] = previous_hash
            result.conflicts.append(key)
            return
        if not update_managed and not refresh_owned:
            managed_hashes[key] = existing_hash
            result.pending_updates.append(key)
            return

    action = result.created if existing_hash is None else result.updated
    action.append(key)
    managed_hashes[key] = desired_hash
    if not result.dry_run:
        _atomic_write(destination, content, executable=executable)


def _ensure_gitignore(root: Path, *, result: BootstrapResult, dry_run: bool) -> None:
    path = workspace_path(root, Path(".gitignore"))
    if path.exists() and not path.is_file():
        result.conflicts.append(GITIGNORE_RESULT_KEY)
        return
    existing = path.read_text(encoding="utf-8") if path.is_file() else ""
    ignored_paths = (
        ".pstack/state/",
        ".pstack/tmp/",
        ".pstack/projectctl/.venv/",
        ".pk-stack-maintenance/",
    )
    migrated = _migrate_gitignore_managed_blocks(existing)
    if migrated is not None:
        content = migrated
    elif all(gitignore_has_entry(existing, ignored_path) for ignored_path in ignored_paths):
        result.unchanged.append(GITIGNORE_RESULT_KEY)
        return
    else:
        prefix = "" if not existing or existing.endswith("\n") else "\n"
        separator = "" if not existing else "\n"
        content = f"{existing}{prefix}{separator}{GITIGNORE_BLOCK}"
    if content == existing:
        result.unchanged.append(GITIGNORE_RESULT_KEY)
        return
    if path.exists():
        result.updated.append(GITIGNORE_RESULT_KEY)
    else:
        result.created.append(GITIGNORE_RESULT_KEY)
    if not dry_run:
        _atomic_write(path, content.encode(), executable=False)


def _migrate_gitignore_managed_blocks(text: str) -> str | None:
    """Replace legacy/current generated blocks with one canonical in-place block."""

    lines = text.splitlines()
    current = GITIGNORE_BLOCK.splitlines()
    legacy = LEGACY_GITIGNORE_BLOCK.splitlines()

    def block_length(index: int) -> int:
        if lines[index : index + len(current)] == current:
            return len(current)
        if lines[index : index + len(legacy)] == legacy:
            return len(legacy)
        return 0

    output: list[str] = []
    found = False
    inserted = False
    index = 0
    while index < len(lines):
        length = block_length(index)
        if not length:
            output.append(lines[index])
            index += 1
            continue
        found = True
        if not inserted:
            output.extend(current)
            inserted = True
        index += length
        following = index
        while following < len(lines) and not lines[following]:
            following += 1
        if following < len(lines) and block_length(following):
            index = following

    if not found:
        return None
    normalized = "\n".join(output)
    return normalized + ("\n" if text.endswith("\n") else "")


def gitignore_has_entry(text: str, entry: str) -> bool:
    """Return whether ``entry`` is a real, uncommented gitignore pattern."""

    return any(
        line.strip() == entry
        for line in text.splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    )


def _existing_parent_blocker(root: Path, relative: Path) -> str | None:
    """Return the first existing non-directory parent of a managed file."""

    current = root
    for part in relative.parent.parts:
        current /= part
        if current.exists() and not current.is_dir():
            return current.relative_to(root).as_posix()
    return None


def _atomic_write(path: Path, content: bytes, *, executable: bool) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        mode = 0o755 if executable else 0o644
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise


def _write_if_changed(path: Path, content: bytes, *, executable: bool) -> None:
    if path.is_file() and path.read_bytes() == content:
        path.chmod(0o755 if executable else 0o644)
        return
    _atomic_write(path, content, executable=executable)


def _hash(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path.cwd())
    parser.add_argument("--power-root", type=Path)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument(
        "--update-managed",
        action="store_true",
        help="replace only files matching the prior receipt after reviewing a dry run",
    )
    parser.add_argument("--output", choices=("json", "text"), default="text")
    args = parser.parse_args(argv)
    try:
        result = bootstrap_project(
            args.root,
            power_root=args.power_root,
            dry_run=args.dry_run,
            update_managed=args.update_managed,
        )
    except (OSError, ValueError) as exc:
        payload = {"ok": False, "error": str(exc), "error_type": type(exc).__name__}
        if args.output == "json":
            print(json.dumps(payload, indent=2, sort_keys=True))
        else:
            print(f"error: {exc}", file=sys.stderr)
        raise SystemExit(2) from None
    if args.output == "json":
        print(json.dumps(result.to_dict(), indent=2, sort_keys=True))
    else:
        print(f"{DISPLAY_NAME} setup {'would update' if args.dry_run else 'updated'} {result.root}")
        for label in (
            "created",
            "updated",
            "pending_updates",
            "stale_managed",
            "unchanged",
            "conflicts",
        ):
            values = getattr(result, label)
            print(f"{label}: {len(values)}")
            for value in values:
                print(f"  - {value}")
        for note in result.notes:
            print(f"note: {note}")
    if not result.ok:
        sys.exit(2)


if __name__ == "__main__":
    main()
